  function resolveLang(p) {
    const explicit = typeof p === 'string' && BY_CODE_LOWER.get(p.toLowerCase());
    if (explicit) return explicit;
    const navs = Array.isArray(navigator.languages) && navigator.languages.length
      ? navigator.languages
      : [navigator.language || 'en'];
    // The APK can have its own system language on Android 13+, independent of WebView's defaults.
    const native = Array.isArray(window.__phoneboxLanguages) ? window.__phoneboxLanguages : [];
    for (const raw of [...native, ...navs]) {
      if (!raw) continue;
      const lower = String(raw).toLowerCase().replace(/_/g, '-');
      // Check the full tag first: a hyphenated code like pt-BR has its own entry distinct from the
      // base-stripped pt (Portugal), so stripping to the base first would always match the wrong one.
      const exact = BY_CODE_LOWER.get(lower);
      if (exact) return exact;
      // Any other Portuguese (pt, pt-PT, pt-AO…) reads Brazilian Portuguese: it is the only one left.
      const base = lower.split('-')[0];
      if (base === 'pt') return 'pt-BR';
      const match = BY_CODE_LOWER.get(base);
      if (match) return match;
    }
    return 'en';
  }

  function applyLanguageAttributes() {
    if (typeof document === 'undefined') return;
    document.documentElement.lang = active;
  }

  function setLang(nextPref) {
    pref = (typeof nextPref === 'string' && BY_CODE_LOWER.get(nextPref.toLowerCase())) || 'auto';
    const prev = active;
    active = resolveLang(pref);
    try { localStorage.setItem('pb-lang', pref); } catch (_) {}
    applyLanguageAttributes();
    return active !== prev;
  }

  function getLang() { return active; }
  function getPref() { return pref; }
  function getLocale() { return BY_CODE.get(active).locale; }

  function t(key, vars) {
    const dict = STRINGS[active] || STRINGS.en;
    let s = dict[key];
    if (s === undefined) s = STRINGS.en[key];
    if (s === undefined) return key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.split(`{${k}}`).join(v == null ? '' : String(v));
      }
    }
    return s;
  }

  /** Translate a catalog string (a widget or template name, description, option label or choice) by its
   *  English text. The catalog itself has no keys; anything missing stays English. */
  function tc(text) {
    if (!text) return text;
    const dict = CATALOG[active];
    // own entries only: text such as "constructor" must not pick up Object's inherited members
    if (!dict || !Object.prototype.hasOwnProperty.call(dict, text)) return text;
    return dict[text];
  }

  /** Translate a panel literal by its English text (see PANEL); anything missing stays English. */
  function tp(text) {
    if (!text) return text;
    const dict = PANEL[active];
    // own entries only: text such as "constructor" must not pick up Object's inherited members
    if (!dict || !Object.prototype.hasOwnProperty.call(dict, text)) return text;
    return dict[text];
  }

  function applyDom(root = document) {
    if (!root) return;
    for (const el of root.querySelectorAll('[data-i18n]')) {
      el.textContent = t(el.dataset.i18n);
    }
    // A paragraph that carries inline <b>, <i>, <code> or a <span id> cannot use data-i18n: textContent would drop the
    // markup. Those elements are marked data-i18n-html and their translation is the original markup (with the English
    // replaced), so the installed copy is written as HTML. The source is a static file in this bundle, not input.
    for (const el of root.querySelectorAll('[data-i18n-html]')) {
      const html = t(el.dataset.i18nHtml);
      if (html !== el.dataset.i18nHtml) el.innerHTML = html;
    }
    for (const el of root.querySelectorAll('[data-i18n-placeholder]')) {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    }
    for (const el of root.querySelectorAll('[data-i18n-title]')) {
      el.title = t(el.dataset.i18nTitle);
    }
    for (const el of root.querySelectorAll('[data-i18n-aria]')) {
      el.setAttribute('aria-label', t(el.dataset.i18nAria));
    }
  }

  function populateSelect(sel, includeAuto = true) {
    if (!sel) return;
    const prev = sel.value;
    sel.replaceChildren();
    if (includeAuto) {
      const opt = document.createElement('option');
      opt.value = 'auto';
      opt.textContent = t('lang.auto');
      sel.appendChild(opt);
    }
    for (const lang of LANGUAGES) {
      const opt = document.createElement('option');
      opt.value = lang.code;
      opt.textContent = lang.nativeName;
      opt.lang = lang.code;
      sel.appendChild(opt);
    }
    if (prev && [...sel.options].some((o) => o.value === prev)) sel.value = prev;
  }

